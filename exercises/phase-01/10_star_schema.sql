-- Date dimension generated, not loaded: one row per calendar day. Smart key yyyymmdd.
CREATE TABLE dim_date AS
SELECT CAST(date_format(d, 'yyyyMMdd') AS INT) AS date_sk,
       d                                       AS date,
       year(d)                                 AS year,
       quarter(d)                              AS quarter,
       month(d)                                AS month,
       date_format(d, 'MMMM')                  AS month_name,
       dayofweek(d)                            AS day_of_week,     -- 1 = Sunday ... 7 = Saturday
       dayofweek(d) IN (1, 7)                  AS is_weekend
FROM (SELECT explode(sequence(DATE'2026-01-01', DATE'2026-12-31', INTERVAL 1 DAY)) AS d);

-- COMMAND ----------

-- STAGING (would be silver_order_lines in a real pipeline) ----------------
CREATE OR REPLACE TEMP VIEW stg_order_lines AS
SELECT * FROM VALUES
  (1001, 1, DATE'2026-10-16', 'C1', 'P1', 2, 50.00, 0.00),
  (1001, 2, DATE'2026-10-16', 'C1', 'P7', 1, 19.90, 0.00),
  (1002, 1, DATE'2026-10-16', 'C2', 'P9', 3, 15.00, 5.00),
  (1003, 1, DATE'2026-10-17', 'C9', 'P1', 1, 50.00, 0.00),   -- customer C9 not in dim yet
  (1004, 1, DATE'2026-10-17', 'C3', 'P9', 1, 15.00, 0.00)
AS t(order_id, line_no, order_date, customer_id, product_id, quantity, unit_price, discount);

-- FACT -----------------------------------------------------------------------
CREATE TABLE fact_order_line (
  order_id     INT,              -- degenerate dimension: an identifier with no dimension table of its own
  line_no      INT,
  date_sk      INT,
  customer_sk  BIGINT,
  product_sk   BIGINT,
  quantity     INT,              -- additive
  unit_price   DECIMAL(10,2),    -- non-additive (never SUM prices)
  discount     DECIMAL(10,2),    -- additive
  line_amount  DECIMAL(12,2)     -- additive: quantity * unit_price - discount
);

-- Surrogate-key lookup: natural key -> surrogate key; unknown -> -1 so no fact row is lost.
INSERT INTO fact_order_line
SELECT  s.order_id,
        s.line_no,
        CAST(date_format(s.order_date, 'yyyyMMdd') AS INT)  AS date_sk,
        COALESCE(c.customer_sk, -1)                         AS customer_sk,
        COALESCE(p.product_sk, -1)                          AS product_sk,
        s.quantity,
        s.unit_price,
        s.discount,
        s.quantity * s.unit_price - s.discount              AS line_amount
FROM    stg_order_lines s
LEFT JOIN dim_customer c ON s.customer_id = c.customer_id
LEFT JOIN dim_product  p ON s.product_id  = p.product_id;

-- COMMAND ----------

-- QUERY: revenue by month, customer segment and product category ---------------
SELECT  d.year, d.month_name,
        c.segment,
        p.category,
        SUM(f.line_amount)          AS revenue,
        SUM(f.quantity)             AS units,
        COUNT(DISTINCT f.order_id)  AS orders
FROM    fact_order_line f
JOIN    dim_date     d ON f.date_sk     = d.date_sk
JOIN    dim_customer c ON f.customer_sk = c.customer_sk
JOIN    dim_product  p ON f.product_sk  = p.product_sk
GROUP BY d.year, d.month_name, c.segment, p.category
ORDER BY revenue DESC;

